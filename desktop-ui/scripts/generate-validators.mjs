import { readFile, writeFile } from 'node:fs/promises';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

// Compile at build time: the webview CSP intentionally prohibits dynamic evaluation.
const schema = JSON.parse(await readFile(new URL('../../desktop-bridge/contract/schema.json', import.meta.url), 'utf8'));
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } });
ajv.addSchema(schema);
const definitions = Object.fromEntries(Object.keys(schema.$defs).map(name => [name, `${schema.$id}#/$defs/${name}`]));
let source = standaloneCode(ajv, definitions);
const imports = new Map();
source = source.replace(/require\("(ajv\/dist\/runtime\/[a-zA-Z0-9_-]+)"\)\.default/g, (_, module) => {
  if (!imports.has(module)) imports.set(module, `runtimeHelper${imports.size}`);
  return `${imports.get(module)}.default`;
});
if (/\brequire\(/.test(source)) throw new Error('Unsupported CommonJS helper in generated validators');
const header = [...imports].map(([module, name]) => `import ${name} from '${module}.js';`).join('\n');
await writeIfChanged(new URL('../src/generated/validators.js', import.meta.url), `// Generated by scripts/generate-validators.mjs; do not edit.\n${header}\n${source}\n`);
await writeIfChanged(new URL('../src/generated/validators.d.ts', import.meta.url), `// Generated by scripts/generate-validators.mjs; do not edit.\nimport type { ValidateFunction } from 'ajv';\n${Object.keys(definitions).map(name => `export declare const ${name}: ValidateFunction;`).join('\n')}\n`);

// Avoid needless writes/rebuilds and Windows sharing conflicts on unchanged output.
async function writeIfChanged(target, content) {
  if (await readFile(target, 'utf8').catch(() => '') !== content) await writeFile(target, content);
}
